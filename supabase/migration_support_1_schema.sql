-- ---------------------------------------------------------------------
-- 11) الدوال المساعدة للصلاحيات (security definer، نفس نمط is_admin الحالية)
--     ملاحظة: لا نلمس is_admin() ولا profiles.role.
-- ---------------------------------------------------------------------
create or replace function public.support_owner_id()
returns uuid
language sql
immutable
set search_path = ''
as $$ select 'be398df3-3918-46e1-abc4-59975ffe716b'::uuid $$;

-- المدير الرئيسي = الـ UUID الثابت + role = admin + غير محظور
create or replace function public.support_is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.id = public.support_owner_id()
      and p.role = 'admin'
      and coalesce(p.is_banned, false) = false
  );
$$;

-- موظف دعم نشط وغير محظور
create or replace function public.support_is_agent()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.support_agents a
    join public.profiles p on p.id = a.user_id
    where a.user_id = (select auth.uid())
      and a.is_active
      and coalesce(p.is_banned, false) = false
  );
$$;

create or replace function public.support_is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$ select public.support_is_owner() or public.support_is_agent(); $$;

-- مستخدم مسجّل وغير محظور
create or replace function public.support_user_ok()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and coalesce(p.is_banned, false) = false
  );
$$;

revoke all on function public.support_owner_id()  from public;
revoke all on function public.support_is_owner()  from public;
revoke all on function public.support_is_agent()  from public;
revoke all on function public.support_is_staff()  from public;
revoke all on function public.support_user_ok()   from public;
grant execute on function public.support_owner_id() to authenticated;
grant execute on function public.support_is_owner() to authenticated;
grant execute on function public.support_is_agent() to authenticated;
grant execute on function public.support_is_staff() to authenticated;
grant execute on function public.support_user_ok()  to authenticated;

