-- ---------------------------------------------------------------------
-- 13) إنشاء التذكرة + أول رسالة في Transaction واحدة (يمنع تذكرة بلا رسالة)
--     مع منع الإرسال المكرر عبر p_client_request_id.
--     العميل لا يملك صلاحية INSERT المباشر على support_tickets؛ هذه هي الطريقة الوحيدة.
-- ---------------------------------------------------------------------
create or replace function public.support_create_ticket(
  p_category_id        bigint,
  p_subcategory_id     bigint,
  p_order_id           text,
  p_subject            text,
  p_message            text,
  p_client_request_id  uuid default null
)
returns table (out_ticket_id uuid, out_ticket_number bigint, out_message_id bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := (select auth.uid());
  v_ticket  public.support_tickets%rowtype;
  v_msg     bigint;
  v_subject text;
  v_order   text := nullif(btrim(p_order_id), '');
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if not public.support_user_ok() then
    raise exception 'account_not_allowed' using errcode = '42501';
  end if;
  if p_message is null or char_length(btrim(p_message)) = 0 then
    raise exception 'message_required' using errcode = '22023';
  end if;
  if char_length(p_message) > 10000 then
    raise exception 'message_too_long' using errcode = '22023';
  end if;
  if v_order is not null and char_length(v_order) > 64 then
    raise exception 'invalid_order_id' using errcode = '22023';
  end if;
  if not exists (select 1 from public.support_categories c where c.id = p_category_id and c.is_active) then
    raise exception 'invalid_category' using errcode = '22023';
  end if;
  if p_subcategory_id is not null and not exists (
       select 1 from public.support_subcategories s
       where s.id = p_subcategory_id and s.category_id = p_category_id and s.is_active) then
    raise exception 'invalid_subcategory' using errcode = '22023';
  end if;

  v_subject := left(coalesce(nullif(btrim(p_subject), ''), left(btrim(p_message), 80)), 200);

  -- إرسال مكرر؟ أعد نفس التذكرة بدون إنشاء جديدة
  if p_client_request_id is not null then
    select * into v_ticket from public.support_tickets t
      where t.user_id = v_uid and t.client_request_id = p_client_request_id;
    if found then
      select m.id into v_msg from public.support_messages m where m.ticket_id = v_ticket.id order by m.id limit 1;
      return query select v_ticket.id, v_ticket.ticket_number, v_msg;
      return;
    end if;
  end if;

  begin
    insert into public.support_tickets (user_id, order_id, category_id, subcategory_id, subject, client_request_id)
    values (v_uid, v_order, p_category_id, p_subcategory_id, v_subject, p_client_request_id)
    returning * into v_ticket;

    insert into public.support_messages (ticket_id, message, is_internal)
    values (v_ticket.id, btrim(p_message), false)
    returning id into v_msg;
  exception when unique_violation then
    -- ضغطتان متزامنتان: الأولى فازت، أعد تذكرتها
    select * into v_ticket from public.support_tickets t
      where t.user_id = v_uid and t.client_request_id = p_client_request_id;
    if not found then
      raise;
    end if;
    select m.id into v_msg from public.support_messages m where m.ticket_id = v_ticket.id order by m.id limit 1;
  end;

  return query select v_ticket.id, v_ticket.ticket_number, v_msg;
end;
