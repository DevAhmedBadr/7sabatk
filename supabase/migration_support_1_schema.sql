-- 12.b حماية التذكرة قبل التعديل: updated_at / closed_at / صحة الموظف المعيّن
create or replace function public.support_tickets_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.updated_at := now();

  if new.status is distinct from old.status then
    new.closed_at := case when new.status = 'closed' then now() else null end;
  end if;

  if new.assigned_agent_id is not null
     and new.assigned_agent_id is distinct from old.assigned_agent_id then
    if not (
      new.assigned_agent_id = public.support_owner_id()
      or exists (
        select 1 from public.support_agents a
        where a.user_id = new.assigned_agent_id and a.is_active
      )
    ) then
      raise exception 'invalid_assignee' using errcode = '22023';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists support_tickets_guard_trg on public.support_tickets;
create trigger support_tickets_guard_trg before update on public.support_tickets
  for each row execute function public.support_tickets_guard();

-- 12.c سجل تغييرات التذكرة
create or replace function public.support_tickets_log_changes()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid  uuid := (select auth.uid());
  v_role text;
begin
  v_role := case
    when v_uid is null then 'system'
    when v_uid = new.user_id then 'customer'
    when public.support_is_owner() then 'admin'
    when public.support_is_agent() then 'agent'
    else 'unknown'
  end;

  if tg_op = 'INSERT' then
    insert into public.support_ticket_events (ticket_id, actor_id, actor_role, event_type, new_value)
    values (new.id, v_uid, v_role, 'created', new.status);
    return new;
  end if;

  if new.status is distinct from old.status then
    insert into public.support_ticket_events (ticket_id, actor_id, actor_role, event_type, old_value, new_value)
    values (new.id, v_uid, v_role,
            case when new.status = 'closed' then 'closed'
                 when old.status = 'closed' then 'reopened'
                 else 'status_changed' end,
            old.status, new.status);
  end if;
  if new.priority is distinct from old.priority then
    insert into public.support_ticket_events (ticket_id, actor_id, actor_role, event_type, old_value, new_value)
    values (new.id, v_uid, v_role, 'priority_changed', old.priority, new.priority);
  end if;
  if new.assigned_agent_id is distinct from old.assigned_agent_id then
    insert into public.support_ticket_events (ticket_id, actor_id, actor_role, event_type, old_value, new_value)
    values (new.id, v_uid, v_role, 'assigned', old.assigned_agent_id::text, new.assigned_agent_id::text);
  end if;
  if new.category_id is distinct from old.category_id then
    insert into public.support_ticket_events (ticket_id, actor_id, actor_role, event_type, old_value, new_value)
    values (new.id, v_uid, v_role, 'category_changed', old.category_id::text, new.category_id::text);
  end if;
  return new;
end;
$$;

drop trigger if exists support_tickets_log_trg on public.support_tickets;
create trigger support_tickets_log_trg after insert or update on public.support_tickets
  for each row execute function public.support_tickets_log_changes();

-- 12.d تجهيز الرسالة: المرسل والدور يُحددان من الخادم دائمًا (لا يثق بالعميل)
create or replace function public.support_messages_prepare()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := (select auth.uid());
  v_ticket public.support_tickets%rowtype;
begin
  select * into v_ticket from public.support_tickets t where t.id = new.ticket_id;
  if not found then
    raise exception 'ticket_not_found' using errcode = '23503';
  end if;

  if v_uid is not null then
    new.sender_id := v_uid;
    if v_ticket.user_id = v_uid then
      new.sender_role := 'customer';
    elsif public.support_is_owner() then
      new.sender_role := 'admin';
    elsif public.support_is_agent() then
      new.sender_role := 'agent';
    else
      raise exception 'not_allowed' using errcode = '42501';
    end if;

    if new.sender_role = 'customer' and v_ticket.status = 'closed' then
      raise exception 'ticket_closed' using errcode = '42501';
    end if;
  elsif new.sender_role is null then
    new.sender_role := 'system';     -- service role / SQL editor
  end if;

  return new;
end;
$$;

drop trigger if exists support_messages_prepare_trg on public.support_messages;
create trigger support_messages_prepare_trg before insert on public.support_messages
  for each row execute function public.support_messages_prepare();

-- 12.e بعد الرسالة العامة: تحديث التذكرة (آخر رسالة + انتقال الحالة تلقائيًا)
--     الملاحظات الداخلية لا تلمس صف التذكرة نهائيًا (حتى لا يُكشف توقيتها للعميل).
create or replace function public.support_messages_after_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.is_internal then
    return new;
  end if;

  update public.support_tickets t
  set last_message_at   = new.created_at,
      last_message_role = new.sender_role,
      status = case
        when new.sender_role = 'customer' and t.status in ('waiting_customer','resolved') then 'open'
        when new.sender_role in ('agent','admin') and t.status = 'open' then 'in_progress'
        else t.status
      end
  where t.id = new.ticket_id;

  return new;
end;
$$;

drop trigger if exists support_messages_after_insert_trg on public.support_messages;
create trigger support_messages_after_insert_trg after insert on public.support_messages
  for each row execute function public.support_messages_after_insert();

-- 12.f تجهيز المرفق: يجب أن يتبع رسالة من نفس التذكرة أرسلها المستخدم نفسه (حد أقصى 5 مرفقات للرسالة)
create or replace function public.support_attachments_prepare()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_msg public.support_messages%rowtype;
begin
  select * into v_msg from public.support_messages m where m.id = new.message_id;
  if not found or v_msg.ticket_id <> new.ticket_id then
    raise exception 'message_ticket_mismatch' using errcode = '23503';
  end if;

  if v_uid is not null then
    if v_msg.sender_id is distinct from v_uid then
      raise exception 'not_allowed' using errcode = '42501';
    end if;
    new.uploaded_by := v_uid;
  end if;

  if (select count(*) from public.support_attachments a where a.message_id = new.message_id) >= 5 then
    raise exception 'too_many_attachments' using errcode = '22023';
  end if;

  return new;
end;
$$;

drop trigger if exists support_attachments_prepare_trg on public.support_attachments;
create trigger support_attachments_prepare_trg before insert on public.support_attachments
  for each row execute function public.support_attachments_prepare();

