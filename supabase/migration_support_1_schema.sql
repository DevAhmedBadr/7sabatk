-- =====================================================================
-- 7sabatk Support System — المرحلة 2 / الملف 1 من 3
-- الجداول + الفهارس + الدوال المساعدة + الـ Triggers + دالة إنشاء التذكرة
--
-- إضافي فقط: لا يحذف ولا يعدّل أي جدول أو بيانات موجودة.
-- آمن لإعادة التشغيل (create ... if not exists / create or replace).
-- شغّله مرة واحدة في Supabase → SQL Editor، ثم الملف 2 ثم الملف 3.
-- =====================================================================
begin;

-- ---------------------------------------------------------------------
-- 1) الفئات والفئات الفرعية
-- ---------------------------------------------------------------------
create table if not exists public.support_categories (
  id          bigint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9_]{2,60}$'),
  name_ar     text not null check (char_length(btrim(name_ar)) between 1 and 120),
  name_en     text not null check (char_length(btrim(name_en)) between 1 and 120),
  is_active   boolean not null default true,
  sort_order  integer not null default 100,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.support_subcategories (
  id          bigint generated by default as identity primary key,
  category_id bigint not null references public.support_categories(id) on delete restrict,
  slug        text not null check (slug ~ '^[a-z0-9_]{2,60}$'),
  name_ar     text not null check (char_length(btrim(name_ar)) between 1 and 120),
  name_en     text not null check (char_length(btrim(name_en)) between 1 and 120),
  is_active   boolean not null default true,
  sort_order  integer not null default 100,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (category_id, slug),
  unique (id, category_id)            -- مطلوب للمفتاح الأجنبي المركّب في التذاكر
);

-- ---------------------------------------------------------------------
-- 2) موظفو الدعم (دور Support Agent منفصل عن profiles.role)
--    وفيه إعدادات الإشعارات لكل موظف.
-- ---------------------------------------------------------------------
create table if not exists public.support_agents (
  user_id                      uuid primary key references public.profiles(id) on delete cascade,
  is_active                    boolean not null default true,
  receive_new_ticket_emails    boolean not null default true,
  receive_inapp_notifications  boolean not null default true,
  added_by                     uuid references public.profiles(id) on delete set null,
  created_at                   timestamptz not null default now(),
  updated_at                   timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 3) التذاكر
--    id = uuid (روابط غير قابلة للتخمين) + ticket_number رقم تسلسلي فريد للعرض.
--    order_id نص اختياري بدون مفتاح أجنبي (لا يوجد جدول طلبات حاليًا).
-- ---------------------------------------------------------------------
create table if not exists public.support_tickets (
  id                 uuid primary key default gen_random_uuid(),
  ticket_number      bigint generated always as identity (start with 1001) unique,
  user_id            uuid not null references public.profiles(id) on delete cascade,
  order_id           text check (order_id is null or char_length(btrim(order_id)) between 1 and 64),
  category_id        bigint not null references public.support_categories(id) on delete restrict,
  subcategory_id     bigint,
  subject            text not null check (char_length(btrim(subject)) between 1 and 200),
  status             text not null default 'open'
                       check (status in ('open','in_progress','waiting_customer','resolved','closed')),
  priority           text not null default 'normal'
                       check (priority in ('low','normal','high','urgent')),
  assigned_agent_id  uuid references public.profiles(id) on delete set null,
  client_request_id  uuid,                      -- لمنع الإرسال المكرر
  last_message_at    timestamptz,
  last_message_role  text check (last_message_role is null or last_message_role in ('customer','agent','admin','system')),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  closed_at          timestamptz,
  constraint support_tickets_subcategory_fk
    foreign key (subcategory_id, category_id)
    references public.support_subcategories (id, category_id) on delete restrict,
  constraint support_tickets_closed_consistency
    check ((status = 'closed') = (closed_at is not null))
);

-- ---------------------------------------------------------------------
-- 4) الرسائل (is_internal = ملاحظة داخلية لا يراها العميل)
-- ---------------------------------------------------------------------
create table if not exists public.support_messages (
  id                 bigint generated always as identity primary key,
  ticket_id          uuid not null references public.support_tickets(id) on delete cascade,
  sender_id          uuid references public.profiles(id) on delete set null,
  sender_role        text not null check (sender_role in ('customer','agent','admin','system')),
  message            text not null check (char_length(btrim(message)) between 1 and 10000),
  is_internal        boolean not null default false,
  client_request_id  uuid,
  created_at         timestamptz not null default now(),
  constraint support_messages_internal_staff_only
    check (not is_internal or sender_role in ('agent','admin'))
);

-- ---------------------------------------------------------------------
-- 5) المرفقات (JPG / PNG / PDF فقط، حد أقصى 5MB للملف)
-- ---------------------------------------------------------------------
create table if not exists public.support_attachments (
  id           uuid primary key default gen_random_uuid(),
  ticket_id    uuid not null references public.support_tickets(id) on delete cascade,
  message_id   bigint not null references public.support_messages(id) on delete cascade,
  uploaded_by  uuid references public.profiles(id) on delete set null,
  file_name    text not null check (char_length(file_name) between 1 and 255 and file_name !~ '[/\\]'),
  file_path    text not null unique,
  file_type    text not null check (file_type in ('image/jpeg','image/png','application/pdf')),
  file_size    bigint not null check (file_size > 0 and file_size <= 5242880),
  created_at   timestamptz not null default now(),
  constraint support_attachments_path_in_ticket
    check (file_path like ticket_id::text || '/%' and position('..' in file_path) = 0)
);

-- ---------------------------------------------------------------------
-- 6) سجل تغييرات التذكرة (يُكتب بالـ Triggers فقط)
-- ---------------------------------------------------------------------
create table if not exists public.support_ticket_events (
  id          bigint generated always as identity primary key,
  ticket_id   uuid not null references public.support_tickets(id) on delete cascade,
  actor_id    uuid references public.profiles(id) on delete set null,
  actor_role  text not null,
  event_type  text not null check (event_type in
              ('created','status_changed','closed','reopened','priority_changed','assigned','category_changed')),
  old_value   text,
  new_value   text,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 7) الإشعارات الداخلية (الـ Triggers الخاصة بها تُضاف في المرحلة 8)
-- ---------------------------------------------------------------------
create table if not exists public.support_notifications (
  id          bigint generated always as identity primary key,
  user_id     uuid not null references public.profiles(id) on delete cascade,
  ticket_id   uuid not null references public.support_tickets(id) on delete cascade,
  message_id  bigint references public.support_messages(id) on delete set null,
  type        text not null check (type in ('ticket_created','new_reply','customer_reply','status_changed','assigned')),
  is_read     boolean not null default false,
  created_at  timestamptz not null default now(),
  read_at     timestamptz
);

-- ---------------------------------------------------------------------
-- 8) سجل البريد الإلكتروني (لا يحتوي أي بيانات اعتماد)
-- ---------------------------------------------------------------------
create table if not exists public.support_email_log (
  id                 bigint generated always as identity primary key,
  notification_type  text not null check (notification_type in
                     ('ticket_created_customer','ticket_created_staff','agent_reply_customer','customer_reply_staff')),
  ticket_id          uuid references public.support_tickets(id) on delete set null,
  recipient_user_id  uuid references public.profiles(id) on delete set null,
  recipient_email    text not null,
  dedupe_key         text not null unique,          -- يمنع الرسائل المكررة
  status             text not null default 'pending' check (status in ('pending','sent','failed')),
  attempts           integer not null default 0 check (attempts >= 0),
  error_message      text,
  next_retry_at      timestamptz,
  created_at         timestamptz not null default now(),
  sent_at            timestamptz
);

-- ---------------------------------------------------------------------
-- 9) تتبع قراءة المحادثات (آخر وقت قراءة لكل مستخدم في كل تذكرة)
-- ---------------------------------------------------------------------
create table if not exists public.support_ticket_reads (
  ticket_id     uuid not null references public.support_tickets(id) on delete cascade,
  user_id       uuid not null references public.profiles(id) on delete cascade,
  last_read_at  timestamptz not null default now(),
  primary key (ticket_id, user_id)
);

