-- 7sabatk marketplace upgrade (additive; preserves existing listings/users)
begin;

alter table public.listings add column if not exists custom_fields jsonb not null default '{}'::jsonb;
alter table public.profiles add column if not exists is_banned boolean not null default false;
alter table public.profiles add column if not exists avatar_url text;
create unique index if not exists profiles_username_unique on public.profiles (lower(username)) where username is not null and username <> '';

create table if not exists public.listing_fields (
  id bigint generated by default as identity primary key,
  field_key text not null unique,
  label_ar text not null,
  label_en text not null,
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

alter table public.listing_fields enable row level security;
drop policy if exists "Public can read active listing fields" on public.listing_fields;
create policy "Public can read active listing fields" on public.listing_fields for select to anon, authenticated using (is_active or (select public.is_admin()));
drop policy if exists "Admins manage listing fields" on public.listing_fields;
create policy "Admins manage listing fields" on public.listing_fields for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

insert into public.listing_fields(field_key,label_ar,label_en,is_active,sort_order) values
 ('likes_count','عدد اللايكات','Likes',true,10),
 ('videos_count','عدد الفيديوهات','Videos',true,20)
on conflict(field_key) do nothing;

-- Keep the current admin-only listing write policy. The browser never receives service_role.
commit;

notify pgrst, 'reload schema';

-- Add a default-language setting for the storefront.
insert into public.site_settings(key,value) values ('default_language','"auto"'::jsonb)
on conflict (key) do nothing;

-- Allow customers to update only safe profile columns; never grant role/status updates.
revoke update on public.profiles from authenticated;
grant update (full_name, username, avatar_url) on public.profiles to authenticated;
drop policy if exists "Users update their own profile" on public.profiles;
create policy "Users update their own profile" on public.profiles
for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

-- Keep the public profile email copy synchronized when Auth email changes.
create or replace function public.sync_profile_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles set email = new.email where id = new.id;
  return new;
end;
$$;
drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
after update of email on auth.users
for each row when (old.email is distinct from new.email)
execute function public.sync_profile_email();

-- Make account statistics fully configurable from the admin dashboard.
insert into public.listing_fields(field_key,label_ar,label_en,is_active,sort_order) values
 ('followers_count','عدد المتابعين','Followers',true,1),
 ('views_count','متوسط المشاهدات','Average views',true,2),
 ('engagement','معدل التفاعل','Engagement',false,3)
on conflict(field_key) do nothing;

-- Enforce a single store owner at the database-policy helper level.
-- Even if another profile is assigned role='admin', it will not gain write privileges.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.id = 'be398df3-3918-46e1-abc4-59975ffe716b'::uuid
      and p.role = 'admin'
  );
$$;
