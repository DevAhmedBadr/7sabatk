-- Profiles: users can read their own profile; the store owner can read all profiles.
create policy profiles_read_self_or_owner
on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

-- Users may only edit safe profile columns. Role and ban state are not granted to clients.
revoke all on public.profiles from public, anon;
revoke update on public.profiles from authenticated;
grant select on public.profiles to authenticated;
grant update (full_name, username, avatar_url) on public.profiles to authenticated;
create policy profiles_update_self
on public.profiles for update to authenticated
using (id = (select auth.uid()) and coalesce(is_banned, false) = false)
with check (id = (select auth.uid()) and coalesce(is_banned, false) = false);

-- Listings: everyone can browse published offers; only the fixed owner can write.
