  field_key text not null unique,
  label_ar text not null,
  label_en text not null,
  field_type text not null default 'number' check (field_type in ('number','text')),
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);
alter table public.listing_fields add column if not exists field_type text not null default 'number';
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'listing_fields_field_type_check'
      and conrelid = 'public.listing_fields'::regclass
  ) then
    alter table public.listing_fields
      add constraint listing_fields_field_type_check
      check (field_type in ('number','text'));
  end if;
end $$;
alter table public.listing_fields enable row level security;

-- One fixed owner only. A profile role alone is not sufficient for listing management.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.id = 'be398df3-3918-46e1-abc4-59975ffe716b'::uuid
      and p.role = 'admin'
      and coalesce(p.is_banned, false) = false
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Remove older permissive policies on these tables, then install the intended rules.
do $$
declare pol record;
begin
  for pol in select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('profiles','listings','listing_fields','site_settings')
  loop
    execute format('drop policy if exists %I on %I.%I', pol.policyname, pol.schemaname, pol.tablename);
  end loop;
end $$;

